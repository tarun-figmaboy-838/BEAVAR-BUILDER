"""Cuts the water band out of the canal backdrop into js/data/water-texture.js (a WebP data URI).

The moving water (js/gameplay/environment.js) ripples and flows the backdrop's own painted water on
the GPU. A data URI keeps WebGL working even when index.html is opened straight from disk (Chrome
refuses WebGL textures from file:// images). Re-run after changing the backdrop, then tools/build.py.
"""
import base64
import io
import os

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BACKDROP = os.path.join(ROOT, "assets/images/background/canal.png")
OUT = os.path.join(ROOT, "js/data/water-texture.js")
STAGE_W, STAGE_H = 1920, 1080
BAND_TOP_STAGE = 556   # a little above the water's far end (y 568), so the shader never samples outside


def main():
    image = Image.open(BACKDROP).convert("RGB")
    scale = max(STAGE_W / image.width, STAGE_H / image.height)       # object-fit: cover
    top = int(BAND_TOP_STAGE / scale)
    band = image.crop((0, top, image.width, image.height))
    buffer = io.BytesIO()
    band.save(buffer, "WEBP", quality=90, method=6)
    data = base64.b64encode(buffer.getvalue()).decode("ascii")
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("/** Generated by tools/make_water_texture.py from the canal backdrop: its water band, for the moving water. */\n")
        handle.write("export const WATER_TEXTURE = Object.freeze({\n")
        handle.write(f"  top: {top * scale:.2f},          // stage px where the band starts\n")
        handle.write(f"  height: {band.height * scale:.2f},       // stage px the band covers\n")
        handle.write(f"  src: 'data:image/webp;base64,{data}',\n")
        handle.write("});\n")
    print(f"water band {band.width}x{band.height} px -> {len(buffer.getvalue()) / 1e3:.0f} KB WebP ({len(data) / 1e3:.0f} KB inline)")


if __name__ == "__main__":
    main()
